"""Regenerate docs/reference/cli.md and docs/reference/mcp-tools.md from the code.

Run: uv run python scripts/gen_reference.py
tests/test_docs.py fails when the committed pages differ from what this produces.
"""

import asyncio
import json
from pathlib import Path

import click

from freshbooks_tools.cli import cli
from freshbooks_tools.mcp_server import INSTRUCTIONS, server

REFERENCE = Path(__file__).resolve().parent.parent / "docs" / "reference"
HEADER = "<!-- Generated by scripts/gen_reference.py; do not edit by hand. -->\n\n"


def _commands(cmd: click.Command, path: list[str]):
    yield path, cmd
    if isinstance(cmd, click.Group):
        for name in sorted(cmd.commands):
            yield from _commands(cmd.commands[name], path + [name])


def render_cli() -> str:
    out = [HEADER, "# CLI reference\n\nEvery `fb` command and its options, as printed by `--help`.\n"]
    for path, cmd in _commands(cli, ["fb"]):
        ctx = click.Context(cmd, info_name=" ".join(path), terminal_width=88, max_content_width=88)
        out.append(f"\n## `{' '.join(path)}`\n\n```text\n{cmd.get_help(ctx)}\n```\n")
    return "".join(out)


def render_mcp() -> str:
    tools = asyncio.run(server.list_tools())
    out = [
        HEADER,
        "# MCP tools reference\n\n",
        "Tools served by `fb mcp`. Write tools change FreshBooks or local config; "
        "MCP clients normally ask before running them.\n\n",
        "## Server instructions\n\nSent to the client when it connects:\n\n```text\n", INSTRUCTIONS, "```\n",
    ]
    for t in sorted(tools, key=lambda t: t.name):
        kind = "read" if t.annotations and t.annotations.read_only_hint else "write"
        out.append(f"\n## `{t.name}` ({kind})\n\n{(t.description or '').strip()}\n\n")
        props = (t.input_schema or {}).get("properties", {})
        required = set((t.input_schema or {}).get("required", []))
        if props:
            out.append("| Parameter | Type | Default |\n|---|---|---|\n")
            for name, spec in props.items():
                types = spec.get("type") or "/".join(s.get("type", "?") for s in spec.get("anyOf", []))
                default = "required" if name in required else f"`{json.dumps(spec.get('default'))}`"
                out.append(f"| `{name}` | {types} | {default} |\n")
        else:
            out.append("No parameters.\n")
    return "".join(out)


PAGES = {"cli.md": render_cli, "mcp-tools.md": render_mcp}

if __name__ == "__main__":
    REFERENCE.mkdir(parents=True, exist_ok=True)
    for name, render in PAGES.items():
        (REFERENCE / name).write_text(render())
        print(f"wrote docs/reference/{name}")
